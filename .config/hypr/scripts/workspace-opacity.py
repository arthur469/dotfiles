#!/usr/bin/python3
"""Set window opacity on the selected normal workspace; keep desktop panels independent."""
from pathlib import Path
import argparse,json,os,subprocess,tempfile,fcntl

def atomic(path,text):
 path.parent.mkdir(parents=True,exist_ok=True)
 fd,name=tempfile.mkstemp(prefix='.'+path.name,dir=path.parent)
 try:
  with os.fdopen(fd,'w') as f:f.write(text)
  os.chmod(name,0o644);os.replace(name,path)
 finally:
  if os.path.exists(name):os.unlink(name)

def apply(workspace,value,home=Path.home(),reload=True):
 if not isinstance(workspace,int) or workspace<1 or workspace>9999:raise ValueError('Sélectionner un bureau normal')
 if round(value*100) not in range(40,101) or abs(round(value*100)/100-value)>1e-6:raise ValueError('Opacité attendue : 40 à 100 %')
 folder=home/'.config/hypr';folder.mkdir(parents=True,exist_ok=True)
 with (folder/'workspace-opacity.lock').open('a') as lock:
  fcntl.flock(lock,fcntl.LOCK_EX)
  p=folder/'workspace-opacity.json';values=json.loads(p.read_text()) if p.exists() else {}
  assert isinstance(values,dict)
  for k,v in values.items():
   if not k.isdigit() or not 1<=int(k)<=9999 or not isinstance(v,(int,float)) or not .4<=v<=1:raise ValueError('Réglage de bureau invalide')
  values[str(workspace)]=value
  lua='-- Generated by workspace-opacity.py; edit through Super+O.\n'
  for key in sorted(values,key=int):lua+='hl.window_rule({ match = { workspace = '+json.dumps(key)+' }, opacity = '+json.dumps(f'{values[key]:.2f} override')+' })\n'
  atomic(p,json.dumps(values,indent=2)+'\n');atomic(folder/'workspace-opacity.lua',lua)
 if reload:
  subprocess.run(['python3',str(home/'.config/hypr/scripts/window-opacity.py'),'--sync'],check=True,stdout=subprocess.DEVNULL)
 return values

def main():
 p=argparse.ArgumentParser();p.add_argument('--set',type=float);p.add_argument('--workspace',type=int);a=p.parse_args()
 workspace=a.workspace
 if workspace is None:workspace=json.loads(subprocess.check_output(['hyprctl','-j','activeworkspace'],timeout=3))['id']
 if workspace<1:raise ValueError('Le réglage concerne un bureau normal, pas un espace spécial')
 value=a.set
 if value is None:
  subprocess.run(['qs','ipc','-p',str(Path.home()/'.config/quickshell'),'call','opacity','openControl','workspace'],check=True);return
 apply(workspace,value)
 print(f'Bureau {workspace} : {round(value*100)} %')
if __name__=='__main__':
 try:main()
 except Exception as error:
  print(str(error),file=__import__('sys').stderr);raise SystemExit(1)
